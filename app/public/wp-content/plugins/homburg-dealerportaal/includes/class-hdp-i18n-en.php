	/**
	 * Het Engels van een tekst die een beheerder zelf invulde, of leeg.
	 *
	 * @param string $nl De Nederlandse tekst.
	 * @return string
	 */
	public static function vertaal_inhoud( $nl ) {
		$lijst = self::inhoud();
		$nl    = trim( (string) $nl );
		return isset( $lijst[ $nl ] ) ? $lijst[ $nl ] : '';
	}

